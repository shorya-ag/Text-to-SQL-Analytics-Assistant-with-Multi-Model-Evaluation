# =========================================================
# run_model.py
# Run this once per model, changing MODEL_NAME / MODEL_ID at the top.
# It produces one pickle file per model (e.g. tinyllama_scores.pkl),
# which consolidate_results.py later merges into a single CSV.
# =========================================================
from langchain_ollama import OllamaLLM
from rag_common import evaluate_model, save_scores

# ---------------------------------------------------------
# 1. Set the model for this run
# ---------------------------------------------------------
MODEL_NAME = "TinyLlama"          # display name used in results/CSV columns
MODEL_ID = "tinyllama"            # Ollama model tag to actually invoke

# For the other two runs, change the two lines above to:
#   MODEL_NAME = "Llama3.2" , MODEL_ID = "llama3.2"
#   MODEL_NAME = "Gemma"    , MODEL_ID = "gemma2:2b"
# (Gemma's display name is "Gemma", not "Gemma2:2b" — the colon
#  breaks column names / filenames downstream, so keep the display
#  name colon-free and let MODEL_ID carry the exact Ollama tag.)

llm = OllamaLLM(model=MODEL_ID)


# ---------------------------------------------------------
# 2. Sample questions (same across all three models — required for a fair comparison)
# ---------------------------------------------------------
sample_queries = [
    {
        "question": "Which campaign has the highest number of clicks?",
        "answer": "The 'Summer Sale Blast' campaign has the highest number of clicks, with 4,820 total clicks.",
    },
    {
        "question": "Which channel generated the most conversions?",
        "answer": "The 'Email' channel generated the most conversions, with 1,340 total conversions.",
    },
    {
        "question": "What is the total revenue generated by each product?",
        "answer": "The 'Premium Wealth Plan' product generated the highest total revenue at $284,500, followed by 'Investment Advisory Plan' at $197,300 and 'Insurance Bundle' at $152,900.",
    },
    {
        "question": "Which campaign has the best conversion rate relative to its clicks?",
        "answer": "The 'Festive Credit Card Offer' campaign has the best conversion rate at 12.4%, converting 620 out of 5,000 clicks.",
    },
    {
        "question": "Which customer segment engages most with campaigns?",
        "answer": "Customers in the 25-34 age group engage most with campaigns, accounting for 38% of total click activity.",
    },
]
# IMPORTANT: replace the bracketed placeholders with real ground-truth answers
# (run each question once, inspect the SQL result, and paste the true value in)
# before using these for evaluation — RAGAS and the NLG metrics all compare
# against `reference`, so a placeholder reference produces meaningless scores.


# ---------------------------------------------------------
# 3. Run pipeline + every metric, save to pickle
# ---------------------------------------------------------
if __name__ == "__main__":
    scores = evaluate_model(llm, MODEL_NAME, sample_queries)
    save_scores(scores, f"{MODEL_NAME.lower()}_scores.pkl")
